// Builds lib/ir/protocol-models.data.ts from litinoveweedle/SmartIR climate files.
// One command from each file is decoded and identified, then its models are summarised.
import { writeFileSync } from "node:fs";
import { CODECS, type CodecId } from "../lib/ir/formats";
import { identify } from "../lib/ir/index";
import { modelCodes } from "../lib/ir/model-pattern";

const TREE = "https://api.github.com/repos/litinoveweedle/SmartIR/git/trees/master?recursive=1";
const RAW = "https://raw.githubusercontent.com/litinoveweedle/SmartIR/master/";

interface ClimateFile {
  manufacturer?: string;
  supportedModels?: string[];
  supportedController?: string;
  commandsEncoding?: string;
  commands?: unknown;
}

function firstCommand(value: unknown): string | undefined {
  if (typeof value === "string") return value;
  if (!value || typeof value !== "object") return undefined;
  const obj = value as Record<string, unknown>;
  if (typeof obj.off === "string") return obj.off;
  for (const child of Object.values(obj)) {
    const found = firstCommand(child);
    if (found) return found;
  }
  return undefined;
}

function unwrap(command: string) {
  const text = command.trim();
  if (!text.startsWith("{")) return text;
  try {
    const parsed = JSON.parse(text) as { ir_code_to_send?: unknown };
    if (typeof parsed.ir_code_to_send === "string") return parsed.ir_code_to_send;
  } catch {
    // the command is not a JSON wrapper
  }
  return text;
}

function codecOrder(file: ClimateFile, text: string): CodecId[] {
  if (text.startsWith("[")) return ["esphome"];
  if (/^0000(\s|[0-9a-f])/i.test(text)) return ["pronto"];
  if (/^26[0-9a-f]+$/i.test(text)) return ["broadlinkHex", "broadlink"];
  if (file.supportedController === "ESPHome") return ["esphome", "broadlink", "tuya"];
  if (file.supportedController === "UFOR11" || file.supportedController === "ZHA" || file.supportedController === "MQTT") {
    return ["tuya", "broadlink"];
  }
  if (file.commandsEncoding === "Pronto") return ["pronto", "broadlink"];
  if (file.commandsEncoding === "Hex") return ["broadlinkHex", "broadlink", "tuya"];
  return ["broadlink", "tuya", "pronto"];
}

function matchedProtocol(file: ClimateFile, command: string) {
  const text = unwrap(command);
  for (const codec of codecOrder(file, text)) {
    try {
      const pulses = CODECS[codec].decode(text);
      const hits = pulses.length > 8 ? identify(pulses) : [];
      if (!hits.length) continue;
      const exact = hits.filter((h) => h.bytes.length * 8 === h.protocol.bits);
      const pool = exact.length ? exact : hits;
      return pool.sort((a, b) => b.protocol.bits - a.protocol.bits || a.protocol.id.localeCompare(b.protocol.id))[0].protocol.id;
    } catch {
      // this codec cannot read the command
    }
  }
  return undefined;
}

async function climateFiles() {
  const tree = (await (await fetch(TREE, { headers: { "user-agent": "aircon-ir-coder" } })).json()) as {
    tree: { path: string; type: string }[];
  };
  return tree.tree.filter((e) => e.type === "blob" && /^codes\/climate\/\d+\.json$/.test(e.path)).map((e) => e.path);
}

async function main() {
  const paths = await climateFiles();
  const byProtocol = new Map<string, string[]>();
  let identified = 0;
  const missed: string[] = [];
  const queue = [...paths];
  async function worker() {
    for (let path = queue.shift(); path; path = queue.shift()) {
      const file = (await (await fetch(RAW + path)).json()) as ClimateFile;
      const command = firstCommand(file.commands);
      const id = command ? matchedProtocol(file, command) : undefined;
      if (id) {
        identified++;
        byProtocol.set(id, [...(byProtocol.get(id) ?? []), ...(file.supportedModels ?? [])]);
      } else missed.push(path);
      if ((identified + missed.length) % 25 === 0) console.log(`${identified + missed.length}/${paths.length}`);
    }
  }
  await Promise.all(Array.from({ length: 8 }, worker));

  const lines = [...byProtocol.entries()]
    .map(([id, models]) => [id, modelCodes(models).sort((a, b) => a.localeCompare(b))] as const)
    .filter(([, models]) => models.length)
    .sort((a, b) => a[0].localeCompare(b[0]));
  const body = lines.map(([id, models]) => `  ${JSON.stringify(id)}: [${models.map((m) => JSON.stringify(m)).join(", ")}],`).join("\n");
  writeFileSync(
    new URL("../lib/ir/protocol-models.data.ts", import.meta.url),
    `// Generated by scripts/gen-protocol-models.ts from litinoveweedle/SmartIR codes/climate.\n` +
      `// Each value is the supportedModels whose codes identify as that protocol.\n` +
      `export const PROTOCOL_MODELS: Record<string, string[]> = {\n${body}\n};\n`,
  );
  console.log(`${identified}/${paths.length} files identified, ${lines.length} protocols, ${missed.length} unread`);
  if (missed.length) console.log(missed.join("\n"));
}

main();
