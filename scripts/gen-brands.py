"""Regenerates lib/ir/brands.data.ts from IRremoteESP8266's SupportedProtocols.md.

Usage: python3 scripts/gen-brands.py path/to/SupportedProtocols.md

Only rows with detailed A/C support are kept. A model tagged "(DAIKIN2)" maps to that protocol;
a tag naming a remote model ("(ARRAH2E)", "(A903)") becomes a variant hint; untagged models list
every protocol implemented from the same source file as candidates to try.
"""

import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
IMPLEMENTED = {p.stem for p in (ROOT / "lib/ir/protocols").glob("*.ts") if not p.stem.startswith("_") and p.stem != "index" and not p.stem.endswith(".test")}

FAMILY = {
    "Airton": ["airton"], "Airwell": ["airwell"], "Amcor": ["amcor"], "Argo": ["argo"], "Bosch": ["bosch144"],
    "Carrier": ["carrier_ac64"], "Coolix": ["coolix"], "Corona": ["corona_ac"],
    "Daikin": ["daikin", "daikin2", "daikin64", "daikin128", "daikin152", "daikin160", "daikin176", "daikin216", "daikin312"],
    "Delonghi": ["delonghi_ac"], "Ecoclim": ["ecoclim"], "Electra": ["electra_ac"], "Eurom": ["eurom"],
    "Fujitsu": ["fujitsu_ac"], "Goodweather": ["goodweather"], "Gree": ["gree"],
    "Haier": ["haier_ac", "haier_ac_yrw02", "haier_ac160", "haier_ac176"],
    "Hitachi": ["hitachi_ac", "hitachi_ac1", "hitachi_ac264", "hitachi_ac296", "hitachi_ac344", "hitachi_ac424"],
    "Kelon": ["kelon"], "Kelvinator": ["kelvinator"], "LG": ["lg", "lg2"], "Midea": ["midea"], "Mirage": ["mirage"],
    "Mitsubishi": ["mitsubishi_ac", "mitsubishi112", "mitsubishi136"],
    "MitsubishiHeavy": ["mitsubishi_heavy_88", "mitsubishi_heavy_152"], "Neoclima": ["neoclima"],
    "Panasonic": ["panasonic_ac", "panasonic_ac32"], "Rhoss": ["rhoss"], "Samsung": ["samsung_ac"],
    "Sanyo": ["sanyo_ac", "sanyo_ac88"], "Sharp": ["sharp_ac"], "Tcl": ["tcl112ac"], "Technibel": ["technibel_ac"],
    "Teco": ["teco"], "Teknopoint": ["teknopoint"], "Toshiba": ["toshiba_ac"], "Transcold": ["transcold"],
    "Trotec": ["trotec", "trotec_3550"], "Truma": ["truma"], "Vestel": ["vestel_ac"], "Voltas": ["voltas"],
    "Whirlpool": ["whirlpool_ac"], "York": ["york"],
}
NOT_AC = re.compile(r"\b(TV|Projector|Soundbar|Bluray|Stand Fan|transmitter IC|disabled)\b", re.I)


def link_text(cell: str) -> str:
    return re.sub(r"\*|\[([^\]]*)\]\([^)]*\)", r"\1", cell).strip()


def resolve(source: str, model: str):
    """Returns (candidate protocol ids, variant hint). An empty list means a sub-protocol we don't cover."""
    family = FAMILY[source]
    tag = re.search(r"\(([^()]*)\)\s*$", model) or re.search(r"\[(\w+) remote\]", model)
    if not tag:
        return family, None
    text = tag.group(1).strip()
    if text in ("88 bit", "152 bit"):
        return [f"mitsubishi_heavy_{text.split()[0]}"], None
    head, _, rest = text.partition(" ")
    if head.lower() in family:
        variant = rest.strip(" -").split("/")[0].split(" & ")[0]
        return [head.lower()], variant or None
    if re.fullmatch(r"[A-Z][A-Z0-9_]+", head) and head.lower().startswith(source.lower()[:4]):
        return [], None
    return family, text


def main(md: str):
    brands: dict[str, list[dict]] = {}
    for line in pathlib.Path(md).read_text().splitlines():
        if not line.startswith("| ["):
            continue
        proto, brand, models, ac_models, detailed = [c.strip() for c in line.strip().strip("|").split("|")]
        if detailed != "Yes":
            continue
        source = link_text(proto)
        if source not in FAMILY:
            continue
        for model in models.split("<BR>"):
            model = model.strip()
            if not model or NOT_AC.search(model):
                continue
            protocols, variant = resolve(source, model)
            protocols = [p for p in protocols if p in IMPLEMENTED]
            if not protocols:
                continue
            name = re.sub(r"\s*\([^()]*\)\s*$", "", model).strip()
            entry = {"model": name, "protocols": protocols}
            if variant:
                entry["variant"] = variant
            brands.setdefault(link_text(brand), []).append(entry)

    out = ROOT / "lib/ir/brands.data.ts"
    body = json.dumps(dict(sorted(brands.items(), key=lambda kv: kv[0].lower())), indent=2, ensure_ascii=False)
    out.write_text(
        "// Generated by scripts/gen-brands.py from IRremoteESP8266 SupportedProtocols.md (LGPL-2.1 project; facts only).\n"
        "// https://github.com/crankyoldgit/IRremoteESP8266/blob/master/SupportedProtocols.md\n"
        f"export const BRAND_MODELS: Record<string, {{ model: string; protocols: string[]; variant?: string }}[]> = {body};\n"
    )
    print(f"{len(brands)} brands, {sum(len(v) for v in brands.values())} models -> {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main(sys.argv[1])
