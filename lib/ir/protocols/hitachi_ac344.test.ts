test("build reproduces TestDecodeHitachiAc344.RealExample", () => {
  assert.equal(hex(p.build(base)), hex(realExample));
  assert.deepEqual(p.parse(realExample), {
    power: true,
    mode: "cool",
    temp: 26,
    fan: "min",
    swingV: "swing",
    swingH: "middle",
  });
});

test("build reproduces TestIRHitachiAc344Class.ReconstructKnownState", () => {
  const s: ClimateState = { ...base, mode: "heat", temp: 17, fan: "auto", swingV: "off" };
  assert.equal(hex(p.build(s)), hex(knownState));
});

test("demodulates the RealExample capture", () => {
  assert.equal(hex(p.demodulate(raw) ?? []), hex(realExample));
});

test("modulate -> demodulate round trip", () => {
  const b = p.build({ ...base, mode: "heat", fan: "max", swingH: "left_max" });
  assert.equal(hex(p.demodulate(p.modulate(b)) ?? []), hex(b));
});

test("parse(build(s)) round trips every capability value", () => {
  const c = p.capabilities;
  for (const mode of c.modes)
    for (const fan of c.fans)
      for (const swingV of c.swingV)
        for (const swingH of c.swingH)
          for (let temp = c.temp.min; temp <= c.temp.max; temp++) {
            if ((mode === "dry" && !["auto", "min", "low"].includes(fan)) || (mode === "fan_only" && fan === "auto")) continue;
            const s = { ...base, mode, fan, swingV, swingH, temp };
            assert.deepEqual(p.parse(p.build(s)), { power: true, mode, temp, fan, swingV, swingH });
          }
});
