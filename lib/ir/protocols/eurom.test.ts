import assert from "node:assert/strict";
import test from "node:test";
import { fromHex, hex } from "../core/bits";
import type { ClimateState } from "../core/types";
import { eurom as p } from "./eurom";
import { roundTripFailures } from "./_roundtrip";

const base: ClimateState = { power: true, mode: "cool", temp: 23, fan: "low", swingV: "off", swingH: "off" };

test("TestEuromAc.ChecksumInitial: off, cool 23°C, fan low", () => {
  const b = p.build({ ...base, power: false });
  assert.equal(b[11], 0x19);
  assert.equal(hex(b), hex(fromHex("18 27 71 00 00 00 00 80 00 80 10 19")));
});

test("TestDecodeEurom.RealExample: cool 23°C, fan low, swing on", () => {
  const want = fromHex("18 27 71 C0 00 00 00 80 00 80 10 25");
  assert.equal(hex(p.build({ ...base, swingV: "swing" })), hex(want));
  assert.equal(p.parse(want).swingV, "swing");
  assert.equal(p.parse(want).temp, 23);
});

test("modulate and demodulate round-trip", () => {
  const b = p.build({ ...base, mode: "heat", temp: 32, fan: "high", sleep: true });
  assert.equal(hex(p.demodulate(p.modulate(b))!), hex(b));
});

test("parse(build) round-trips every capability", () => {
  assert.deepEqual(roundTripFailures(p, base), []);
});

