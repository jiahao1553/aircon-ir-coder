import assert from "node:assert/strict";
import test from "node:test";
import { fromHex, hex } from "../core/bits";
import type { ClimateState } from "../core/types";
import { ecoclim as p } from "./ecoclim";
import { roundTripFailures } from "./_roundtrip";

const base: ClimateState = { power: true, mode: "auto", temp: 11, fan: "auto", swingV: "off", swingH: "off" };

test("kEcoclimDefaultState parses as power off, auto, 11°C, fan auto", () => {
  const raw = fromHex("0A FF FF 00 30 06 11");
  assert.equal(p.parse(raw).power, false);
  assert.equal(p.parse(raw).mode, "auto");
  assert.equal(p.parse(raw).temp, 11);
  assert.equal(p.parse(raw).fan, "auto");
});

test("modulate and demodulate round-trip", () => {
  const b = p.build({ ...base, power: true, mode: "cool", temp: 22, fan: "max" });
  assert.equal(hex(p.demodulate(p.modulate(b))!), hex(b));
  assert.equal(p.modulate(b).filter((_, i) => i % 2 === 0).length > 3, true);
});

test("parse(build) round-trips every capability", () => {
  assert.deepEqual(roundTripFailures(p, { ...base, mode: "cool", temp: 24 }), []);
});

