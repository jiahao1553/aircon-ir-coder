test("build matches TestDecodeHitachiAc296.RealExample apart from the button pair", () => {
  const b = p.build(base);
  // The class always writes button 0x43; this capture carries 0x44.
  assert.deepEqual([b[11], b[12]], [0x43, 0xbc]);
  b[11] = realExample[11];
  b[12] = realExample[12];
  assert.equal(hex(b), hex(realExample));
  assert.deepEqual(p.parse(realExample), { power: true, mode: "auto", fan: "auto" });
});

test("build reproduces the TestIRac.Hitachi296 settings", () => {
  assert.equal(hex(p.build({ ...base, mode: "heat", temp: 20, fan: "low" })), hex(iracHeat20Low));
});

test("demodulates the RealExample capture", () => {
  assert.equal(hex(p.demodulate(raw) ?? []), hex(realExample));
});

test("modulate -> demodulate round trip", () => {
  const b = p.build({ ...base, mode: "cool", temp: 18, fan: "quiet" });
  assert.equal(hex(p.demodulate(p.modulate(b)) ?? []), hex(b));
});

test("parse(build(s)) round trips every capability value", () => {
  const c = p.capabilities;
  for (const mode of c.modes)
    for (const fan of c.fans)
      for (let temp = c.temp.min; temp <= c.temp.max; temp++)
        for (const power of [true, false]) {
          const s = { ...base, power, mode, fan, temp };
          assert.deepEqual(p.parse(p.build(s)), mode === "auto" ? { power, mode, fan } : { power, mode, temp, fan });
        }
});
