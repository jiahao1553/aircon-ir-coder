test("build reproduces the TestIRac.Hitachi settings", () => {
  const s: ClimateState = { ...base, mode: "auto", temp: 22, fan: "medium", swingH: "swing" };
  assert.equal(hex(p.build(s)), hex(iracAuto22));
});

test("build matches TestDecodeHitachiAC.NormalRealExample2 apart from bytes 14-15", () => {
  const b = p.build({ ...base, mode: "heat", temp: 32, fan: "max" });
  // The class reset writes 0x60 into bytes 14 and 15; the captured remote sends 0x00.
  assert.deepEqual([b[14], b[15]], [0x60, 0x60]);
  assert.equal(hex(b.slice(0, 14)), hex(real2.slice(0, 14)));
  assert.equal(hex(b.slice(16, 27)), hex(real2.slice(16, 27)));
  assert.equal(hex(p.demodulate(p.modulate(b)) ?? []), hex(b));
});

test("checksum matches TestIRHitachiAcClass.ChecksumCalculation", () => {
  assert.notEqual(p.demodulate(p.modulate(real1)), null);
  const bad = real1.slice();
  bad[27] = 0x12;
  assert.equal(p.demodulate(p.modulate(bad)), null);
});

test("demodulates the NormalRealExample captures", () => {
  assert.equal(hex(p.demodulate(raw1) ?? []), hex(real1));
  assert.equal(hex(p.demodulate(raw2) ?? []), hex(real2));
  assert.deepEqual(p.parse(real1), { power: true, mode: "cool", temp: 16, fan: "auto", swingV: "off", swingH: "off" });
  assert.deepEqual(p.parse(real2), { power: true, mode: "heat", temp: 32, fan: "max", swingV: "off", swingH: "off" });
});

test("modulate -> demodulate round trip", () => {
  const b = p.build({ ...base, mode: "dry", temp: 25, fan: "medium", swingV: "swing" });
  assert.equal(hex(p.demodulate(p.modulate(b)) ?? []), hex(b));
});

test("parse(build(s)) round trips every capability value", () => {
  const c = p.capabilities;
  for (const mode of c.modes)
    for (const fan of c.fans)
      for (const swingV of c.swingV)
        for (const swingH of c.swingH)
          for (let temp = c.temp.min; temp <= c.temp.max; temp++) {
            if ((mode === "dry" && !["low", "medium"].includes(fan)) || (mode === "fan_only" && fan === "auto")) continue;
            for (const power of [true, false]) {
              const s = { ...base, power, mode, fan, swingV, swingH, temp };
              assert.deepEqual(p.parse(p.build(s)), { power, mode, temp, fan, swingV, swingH });
            }
          }
});
